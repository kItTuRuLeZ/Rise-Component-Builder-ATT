// Generates js/att-logos.js from the AT&T wordmark SVG supplied in
// `ATT Design System/ATT_logo.svg` (kept out of git). Only one lockup and colourway was
// supplied (AT&T Blue #009fdb); a white variant for dark surfaces is derived from it by
// recolouring the same path data, not redrawn.
//
// Usage: node scripts/build-att-logos.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'ATT Design System', 'ATT_logo.svg');

function readLogo(file, { recolor } = {}) {
  let svg = readFileSync(file, 'utf8');
  svg = svg.replace(/<\?xml[^>]*\?>\s*/, '').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
  const box = svg.match(/viewBox="([^"]+)"/);
  if (!box) throw new Error(`${file}: no viewBox`);
  const [, , w, h] = box[1].split(/\s+/).map(Number);
  let inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '')
    .replace(/\sid="[^"]*"/g, '')
    .replace(/\sdata-name="[^"]*"/g, '');
  if (recolor) {
    // Every <path> gets an explicit fill — including any that had none at all (the wordmark
    // letters have no fill attribute in the source and so default to black per the SVG spec;
    // a plain string-replace of the literal blue fill would miss them and leave black text).
    inner = inner
      .replace(/fill="#009fdb"/gi, `fill="${recolor}"`)
      .replace(/<path(?![^>]*\sfill=)/g, `<path fill="${recolor}"`);
  }
  return { viewBox: box[1], aspect: +(w / h).toFixed(4), inner };
}

const logos = {
  fullColor: readLogo(source),
  white: readLogo(source, { recolor: '#FFFFFF' })
};

const out = `// AT&T wordmark logo — GENERATED by scripts/build-att-logos.mjs from the SVG supplied in
// \`ATT Design System/ATT_logo.svg\`. Do not edit by hand.
//   fullColor: as supplied (AT&T Blue #009fdb) — light surfaces.
//   white: the same path data recoloured for dark surfaces (this project has no separate
//   white-variant source file).
// Minimum on-screen height follows this project's general logo convention (32px); no AT&T
// clearspace/minimum-size rule was supplied to check it against.

export const ATT_LOGO_MIN_HEIGHT_PX = 32;

export const ATT_LOGOS = Object.freeze(${JSON.stringify(logos, null, 2)});

/**
 * The AT&T wordmark as an inline SVG. \`tone\`: 'color' (light surfaces) or 'white' (dark
 * surfaces). Height is clamped up to the 32px on-screen minimum.
 */
export function attLogoSvg({ tone = 'color', height = ATT_LOGO_MIN_HEIGHT_PX, className = 'att-logo' } = {}) {
  const logo = ATT_LOGOS[tone === 'white' ? 'white' : 'fullColor'];
  const h = Math.max(ATT_LOGO_MIN_HEIGHT_PX, Number(height) || ATT_LOGO_MIN_HEIGHT_PX);
  const w = Math.round(h * logo.aspect);
  return \`<svg class="\${className}" xmlns="http://www.w3.org/2000/svg" viewBox="\${logo.viewBox}" width="\${w}" height="\${h}" role="img" aria-label="AT&T">\${logo.inner}</svg>\`;
}
`;
writeFileSync(join(root, 'js', 'att-logos.js'), out);
console.log('Wrote js/att-logos.js', Object.entries(logos).map(([k, v]) => `${k} ${v.aspect}`).join(', '));
